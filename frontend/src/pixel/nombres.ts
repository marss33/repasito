// Los peinados se muestran con un número (los gratis primero); el nombre de arriba queda como referencia
const GRATIS = ['pelo-afro', 'pelo-bob', 'pelo-curly-short', 'pelo-long-straight', 'pelo-messy1', 'pelo-plain']
const PEINADOS = [...GRATIS, ...Object.keys(NOMBRES).filter((id) => id.startsWith('pelo-') && !GRATIS.includes(id))]

export function nombresPixel(idioma: 'es' | 'en'): Record<string, string> {
  const i = idioma === 'es' ? 0 : 1
  const peinado = idioma === 'es' ? 'Peinado' : 'Hairstyle'
  return {
    ...Object.fromEntries(Object.entries(NOMBRES).map(([id, n]) => [id, n[i]])),
    ...Object.fromEntries(PEINADOS.map((id, n) => [id, `${peinado} ${n + 1}`])),
  }
}
