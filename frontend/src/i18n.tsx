const TEXTOS: Record<Idioma, Textos> = { es, en }
const CLAVE = 'repaso:idioma'

function idiomaInicial(): Idioma {
  try {
    const guardado = localStorage.getItem(CLAVE)
    if (guardado === 'es' || guardado === 'en') return guardado
  } catch {
    // sin almacenamiento local
  }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'es'
}

interface ValorIdioma {
  idioma: Idioma
  setIdioma: (idioma: Idioma) => void
  t: Textos
}

const ContextoIdioma = createContext<ValorIdioma | null>(null)

export function ProveedorIdioma({ children }: { children: ReactNode }) {
  const [idioma, setIdiomaEstado] = useState<Idioma>(() => {
    const inicial = idiomaInicial()
    establecerIdioma(inicial) // antes del primer pedido al servidor
    return inicial
  })

  useEffect(() => {
    establecerIdioma(idioma)
    document.documentElement.lang = idioma
    document.title = idioma === 'en' ? 'Repasito · Study with your own notes' : 'Repasito · Estudiá con tus apuntes'
    try {
      localStorage.setItem(CLAVE, idioma)
    } catch {
      // sin almacenamiento local
    }
  }, [idioma])

  const setIdioma = useCallback((nuevo: Idioma) => {
    establecerIdioma(nuevo)
    setIdiomaEstado(nuevo)
  }, [])

  return <ContextoIdioma.Provider value={{ idioma, setIdioma, t: TEXTOS[idioma] }}>{children}</ContextoIdioma.Provider>
}

export function useIdioma(): ValorIdioma {
  const valor = useContext(ContextoIdioma)
  if (!valor) throw new Error('useIdioma tiene que usarse dentro de ProveedorIdioma')
  return valor
}

/** Botones ES | EN para cambiar el idioma de toda la app. */
export function SelectorIdioma({ className = '' }: { className?: string }) {
  const { idioma, setIdioma, t } = useIdioma()
  return (
    <div
      className={`inline-flex rounded-lg bg-stone-200/70 p-0.5 text-xs font-semibold dark:bg-stone-800 ${className}`}
      role="group"
      aria-label={t.idioma}
    >
      {(['es', 'en'] as const).map((opcion) => (
        <button
          key={opcion}
          onClick={() => setIdioma(opcion)}
          aria-pressed={idioma === opcion}
          className={`rounded-md px-2 py-1 uppercase transition-colors ${
            idioma === opcion
              ? 'bg-white text-stone-900 shadow-sm dark:bg-stone-950 dark:text-white'
              : 'text-stone-500 hover:text-stone-800 dark:hover:text-stone-200'
          }`}
        >
          {opcion}
        </button>
      ))}
    </div>
  )
}
